// 文字動畫 Preset 的 keyframes，每個字母（或單字）各自套用，由 text-preset 轉為 Web Animations API 的 keyframes
// 數值採 CSS 寫法：位移單位為 px、y 向下為正、旋轉角度順時針為正
// 每段動畫都是「進場 → 停留 → 退場」或可無縫銜接的循環，緩動曲線作用在每一段之間

// 數值可以是函式，依字母序號 i 與字級 size 計算
export type PoseValue = number | ((i: number, size: number) => number)

export interface Pose {
  x?: PoseValue
  y?: PoseValue
  // 往鏡頭方向為正
  z?: PoseValue
  rx?: PoseValue
  ry?: PoseValue
  rz?: PoseValue
  // 等比縮放，與 sx、sy 相乘
  s?: PoseValue
  sx?: PoseValue
  sy?: PoseValue
  skx?: PoseValue
  sky?: PoseValue
  // 透明度
  o?: PoseValue
  // 發光（色票 1 的 text-shadow）
  glow?: PoseValue
  // 模糊（px）
  blur?: PoseValue
  // 長陰影的長度（px）
  shadow?: PoseValue
  // 色差分離的距離（px）
  split?: PoseValue
  // 文字填色的高度 0 ~ 1（搭配 fill 效果）
  fill?: PoseValue
  // 額外字距（em）
  spacing?: PoseValue
  // 顯示範圍（文字寬度的 0 ~ 1），以裁切平面實作
  clipStart?: PoseValue
  clipEnd?: PoseValue
  // 光澤掃過的位置 0 ~ 1（搭配 shine 效果）
  light?: PoseValue
  // 色票索引（0 ~ 4），相鄰影格之間漸變
  color?: number
}

export type Frame = [number, Pose]

