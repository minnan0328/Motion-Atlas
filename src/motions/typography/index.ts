// 文字動畫的十種分類
export const TYPOGRAPHY_GROUPS = [
  'Entrance',
  'Exit',
  'Emphasis',
  'Transform',
  'Reveal',
  'Stagger',
  'Kinetic',
  'Loop',
  'Elastic',
  'Distortion',
] as const
export type TypographyGroup = (typeof TYPOGRAPHY_GROUPS)[number]

type ModuleSource =
  | { kind: 'preset'; preset: TextPreset }
  | { kind: 'standalone'; load: () => Promise<MotionModule> }

interface TypographyEntry {
  id: string
  title: string
  titleEn: string
  description: string
  group: TypographyGroup
  tags: string[]
  principles: PrincipleId[]
  defaults: Partial<MotionParams>
  controls: ControlKey[]
  module: ModuleSource
}

const preset = (value: TextPreset): ModuleSource => ({ kind: 'preset', preset: value })
const standalone = (load: () => Promise<MotionModule>): ModuleSource => ({ kind: 'standalone', load })

